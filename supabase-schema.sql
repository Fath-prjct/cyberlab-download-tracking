-- Run this in Supabase Dashboard > SQL Editor.
-- The service role key is used only by server-side API routes; never expose it in browser code.
create table if not exists public.access_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('page_view', 'download')),
  ip_address text not null default 'unknown',
  user_agent text not null default 'unknown',
  referrer text not null default '',
  path text not null default '/',
  created_at timestamptz not null default now()
);

create index if not exists access_events_created_at_idx
  on public.access_events (created_at desc);
create index if not exists access_events_event_type_idx
  on public.access_events (event_type);

-- Deny direct public table access. Server-side service-role API routes access the table.
alter table public.access_events enable row level security;
revoke all on table public.access_events from anon, authenticated;
